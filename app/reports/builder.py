"""
Report generator for AEGIS-Recon.

Produces JSON and HTML reports from scan data, findings, and analysis.
HTML reports use Jinja2 with autoescaping to prevent XSS from
untrusted banner/CVE text.

Reports include:
- Scan metadata (target, profile, timestamps, tool versions)
- Host and service inventory
- Findings with evidence types and confidence
- Risk scoring with factor explanations
- AI or deterministic analysis summary
- Intel snapshot timestamps for reproducibility
"""

from __future__ import annotations

import json
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from jinja2 import Environment, FileSystemLoader, select_autoescape

from app.core.logging import get_logger

logger = get_logger(__name__)

# Template directory
TEMPLATE_DIR = Path(__file__).parent / "templates"


def build_json_report(
    scan: dict[str, Any],
    hosts: list[dict[str, Any]],
    services: list[dict[str, Any]],
    findings: list[dict[str, Any]],
    analysis: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """
    Build a complete JSON report.

    Args:
        scan: Scan metadata dict.
        hosts: List of host dicts.
        services: List of service dicts.
        findings: List of finding dicts.
        analysis: Optional AI/deterministic analysis.

    Returns:
        Complete report dict.
    """
    report_id = str(uuid.uuid4())
    now = datetime.now(timezone.utc).isoformat()

    # Severity counts
    severity_counts = {"critical": 0, "high": 0, "medium": 0, "low": 0, "informational": 0}
    for f in findings:
        sev = f.get("severity", "informational")
        if sev in severity_counts:
            severity_counts[sev] += 1

    # Evidence type counts
    evidence_counts: dict[str, int] = {}
    for f in findings:
        ev = f.get("evidence_type", "unknown")
        evidence_counts[ev] = evidence_counts.get(ev, 0) + 1

    kev_count = sum(1 for f in findings if f.get("is_kev"))

    report = {
        "report_id": report_id,
        "generated_at": now,
        "aegis_version": "1.0.0",
        "scan": {
            "id": scan.get("id", ""),
            "target": scan.get("target", ""),
            "profile": scan.get("profile", ""),
            "status": scan.get("status", ""),
            "start_time": scan.get("start_time", ""),
            "end_time": scan.get("end_time", ""),
            "nmap_version": scan.get("nmap_version", ""),
            "command_args": scan.get("command_args", ""),
        },
        "summary": {
            "hosts_discovered": len(hosts),
            "hosts_up": scan.get("hosts_up", 0),
            "services_discovered": len(services),
            "findings_total": len(findings),
            "severity_counts": severity_counts,
            "evidence_type_counts": evidence_counts,
            "kev_count": kev_count,
        },
        "hosts": _sanitize_list(hosts),
        "services": _sanitize_list(services),
        "findings": _sanitize_list(findings),
        "analysis": analysis or {},
        "disclaimer": (
            "This report is generated by automated scanning and CVE matching. "
            "Findings labeled as 'hypothesis' require manual verification. "
            "A version match is NOT a confirmed vulnerability. "
            "This report should be reviewed by a qualified security professional."
        ),
    }

    logger.info(
        "json_report_built",
        report_id=report_id,
        findings=len(findings),
        kev=kev_count,
    )

    return report


def build_html_report(
    scan: dict[str, Any],
    hosts: list[dict[str, Any]],
    services: list[dict[str, Any]],
    findings: list[dict[str, Any]],
    analysis: dict[str, Any] | None = None,
) -> str:
    """
    Build an HTML report using Jinja2 templates.

    Autoescaping is ON to prevent XSS from banner/CVE text.

    Returns:
        HTML string.
    """
    env = Environment(
        loader=FileSystemLoader(str(TEMPLATE_DIR)),
        autoescape=select_autoescape(["html"]),
    )

    template = env.get_template("report.html")

    severity_counts = {"critical": 0, "high": 0, "medium": 0, "low": 0, "informational": 0}
    for f in findings:
        sev = f.get("severity", "informational")
        if sev in severity_counts:
            severity_counts[sev] += 1

    kev_count = sum(1 for f in findings if f.get("is_kev"))

    html = template.render(
        report_id=str(uuid.uuid4()),
        generated_at=datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC"),
        scan=scan,
        hosts=hosts,
        services=services,
        findings=findings,
        analysis=analysis or {},
        severity_counts=severity_counts,
        kev_count=kev_count,
        total_findings=len(findings),
        total_services=len(services),
    )

    logger.info("html_report_built", findings=len(findings))
    return html


def _sanitize_list(items: list[dict]) -> list[dict]:
    """Sanitize a list of dicts for JSON output — remove None values."""
    result = []
    for item in items:
        clean = {}
        for k, v in item.items():
            if v is not None:
                clean[k] = v
        result.append(clean)
    return result
